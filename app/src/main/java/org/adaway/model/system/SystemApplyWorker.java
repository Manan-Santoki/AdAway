package org.adaway.model.system;

import android.content.Context;
import android.util.Log;

import androidx.annotation.NonNull;
import androidx.work.Constraints;
import androidx.work.ExistingWorkPolicy;
import androidx.work.NetworkType;
import androidx.work.OneTimeWorkRequest;
import androidx.work.WorkManager;
import androidx.work.Worker;
import androidx.work.WorkerParameters;

import org.adaway.AdAwayApplication;
import org.adaway.model.error.HostErrorException;

import java.io.BufferedReader;
import java.io.FileReader;
import java.io.IOException;

import static org.adaway.util.Constants.ANDROID_SYSTEM_ETC_HOSTS;

/**
 * Makes sure the blocklist is live in system mode: downloads the hosts sources and applies
 * them whenever the system hosts file isn't AdAway's, retrying until it works. Unlike the
 * periodic update, it doesn't depend on the sources having changed.
 */
public class SystemApplyWorker extends Worker {
    private static final String WORK_NAME = "SystemApply";

    public SystemApplyWorker(@NonNull Context context, @NonNull WorkerParameters params) {
        super(context, params);
    }

    /**
     * Queue an apply if blocking isn't active yet. Cheap to call on every start.
     */
    public static void ensureApplied(Context context) {
        if (isApplied()) {
            return;
        }
        Log.i(SystemHosts.TAG, "blocking is not active yet, queueing an apply");
        Constraints constraints = new Constraints.Builder()
                .setRequiredNetworkType(NetworkType.CONNECTED)
                .build();
        OneTimeWorkRequest request = new OneTimeWorkRequest.Builder(SystemApplyWorker.class)
                .setConstraints(constraints)
                .build();
        WorkManager.getInstance(context).enqueueUniqueWork(WORK_NAME, ExistingWorkPolicy.KEEP, request);
    }

    /**
     * @return {@code true} if the system hosts file was generated by AdAway.
     */
    static boolean isApplied() {
        try (BufferedReader reader = new BufferedReader(new FileReader(ANDROID_SYSTEM_ETC_HOSTS))) {
            String line = reader.readLine();
            return line != null && line.startsWith("# This hosts file has been generated by AdAway");
        } catch (IOException exception) {
            Log.w(SystemHosts.TAG, "Failed to read the hosts file", exception);
            return false;
        }
    }

    @NonNull
    @Override
    public Result doWork() {
        AdAwayApplication application = (AdAwayApplication) getApplicationContext();
        try {
            Log.i(SystemHosts.TAG, "downloading hosts sources");
            application.getSourceModel().retrieveHostsSources();
            application.getAdBlockModel().apply();
        } catch (HostErrorException exception) {
            Log.e(SystemHosts.TAG, "applying the blocklist failed, will retry", exception);
            return Result.retry();
        }
        boolean applied = isApplied();
        Log.i(SystemHosts.TAG, "apply finished, blocking active: " + applied);
        return applied ? Result.success() : Result.retry();
    }
}
